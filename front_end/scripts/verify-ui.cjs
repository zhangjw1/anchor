const assert = require('node:assert/strict');
const { mkdir } = require('node:fs/promises');
const { chromium } = require(process.argv[2] || 'playwright');

async function main() {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await mkdir('artifacts', { recursive: true });
  const number = (value) => Number(value.replace(/[^\d.-]/g, ''));
  const text = (id) => page.getByTestId(id).innerText();
  const assertCount = async () => {
    const count = await page.locator('tbody tr').count();
    assert(await page.getByText(`显示 ${count} 条`, { exact: true }).isVisible());
    return count;
  };
  const demo = async (label) => {
    await page.getByRole('group', { name: '演示状态切换' }).getByRole('button', { name: label, exact: true }).click();
    await page.clock.runFor(750);
  };
  const advanceStep = async (index) => {
    await page.clock.runFor(1250);
    await page.getByRole('list', { name: '交易进度' }).locator('li').nth(index).and(page.locator('[aria-current="step"]')).waitFor();
  };
  try {
    await page.clock.install();
    await page.goto('http://localhost:3000/');
    await page.getByTestId('swap-action').getByText('兑换 (Swap)', { exact: true }).waitFor();
    assert.equal(await text('wallet-WETH'), '8.924');
    assert.match(await text('sell-balance'), /8\.924 WETH/);
    assert.equal(number(await text('net-worth')), Number(((12.458 + 8.924) * 3402.12 + 45230).toFixed(2)));
    assert.equal(await page.getByText('Swap 次数', { exact: false }).count(), 4);
    assert.equal(await assertCount(), 12);
    const confirmingRow = page.locator('tbody tr').filter({ hasText: '+240.5k DEGEN' });
    assert.match(await confirmingRow.innerText(), /-500\.00 USDC/);
    assert.match(await confirmingRow.innerText(), /3\/12 确认/);
    assert.equal(await page.locator('tbody').getByText(/\d+\/12 确认/).count(), 2);
    await page.clock.runFor(2000);
    assert.match(await confirmingRow.innerText(), /4\/12 确认/);
    await page.screenshot({ path: 'artifacts/desktop.png' });
    await page.clock.runFor(22000);
    assert.match(await confirmingRow.innerText(), /已确认/);
    assert((await assertCount()) > 12);
    await page.getByTitle('暂停实时推送').click();
    assert.equal(await page.getByTestId('route-quotes').locator(':scope > div').count(), 4);
    const routes = await page.getByTestId('route-quotes').locator(':scope > div').allInnerTexts();
    assert.equal(routes.filter((route) => route.includes('最优')).length, 1);
    assert(routes[1].includes('最优'));
    const quote = number(await page.getByLabel('买入数量', { exact: true }).inputValue());
    const rawQuote = Math.floor(3402.12 * (1 - 0.05 / 100) * (1 - 0.0003) * 1e6) / 1e6;
    assert.equal(quote, Number(rawQuote.toFixed(2)));
    assert.equal(number(await text('minimum-received')), Number((rawQuote * 0.995).toFixed(2)));
    await page.getByRole('button', { name: '修改滑点', exact: true }).click();
    await page.getByRole('button', { name: '1.0%', exact: true }).click();
    assert.equal(number(await text('minimum-received')), Number((rawQuote * 0.99).toFixed(2)));
    await page.getByLabel('自定义滑点').fill('-1');
    assert(await page.getByTestId('swap-action').isDisabled());
    await page.getByLabel('自定义滑点').fill('0');
    assert.equal(number(await text('minimum-received')), quote);
    await page.getByRole('button', { name: '使用最大余额' }).click();
    assert.equal(await page.getByLabel('卖出数量', { exact: true }).inputValue(), '8.924');
    await page.clock.runFor(750);
    await page.getByRole('button', { name: '卖出代币', exact: true }).click();
    await page.getByRole('option', { name: 'USDC', exact: true }).click();
    assert.match(await text('sell-balance'), /45,230\.00 USDC/);
    assert.equal(await page.getByRole('button', { name: '买入代币', exact: true }).innerText(), 'WETH');
    await page.getByRole('button', { name: '演示状态', exact: true }).click();
    await demo('未输入');
    assert.equal(await page.getByLabel('卖出数量', { exact: true }).inputValue(), '');
    assert(await page.getByTestId('swap-action').isDisabled());
    await demo('报价中');
    assert.match(await text('swap-action'), /报价中/);
    assert(await page.getByTestId('swap-action').isDisabled());
    await demo('余额不足');
    assert.match(await text('swap-action'), /余额不足/);
    assert(await page.getByTestId('swap-action').isDisabled());
    await demo('需授权');
    assert.match(await text('swap-action'), /授权 WETH/);
    await page.getByTestId('swap-action').click();
    await page.clock.runFor(1300);
    assert.match(await text('swap-action'), /兑换/);
    await demo('交易失败');
    assert(await page.getByRole('alert').filter({ hasText: 'revert: Too little received' }).isVisible());
    await page.screenshot({ path: 'artifacts/failed.png' });
    await demo('交易进行中');
    assert(await page.getByRole('list', { name: '交易进度' }).isVisible());
    await advanceStep(1);
    await advanceStep(2);
    assert.match(await text('broadcast-hash'), /^0x[0-9a-f]{64}$/);
    await page.screenshot({ path: 'artifacts/progress.png' });
    await advanceStep(3);
    await advanceStep(4);
    assert.equal(await text('wallet-WETH'), '8.924');
    await demo('可兑换');
    const paid = number(await page.getByLabel('卖出数量', { exact: true }).inputValue());
    const received = number(await page.getByLabel('买入数量', { exact: true }).inputValue());
    await page.getByTestId('swap-action').click();
    assert(await page.getByTestId('swap-action').isDisabled());
    assert.equal(await text('wallet-WETH'), '8.924');
    for (let step = 1; step <= 4; step++) await advanceStep(step);
    assert(Math.abs(number(await text('wallet-WETH')) - (8.924 - paid)) < 0.001);
    assert(Math.abs(number(await text('wallet-USDC')) - (45230 + received)) < 0.01);
    const expectedWorth = (12.458 + 8.924 - paid) * 3402.12 + 45230 + received;
    assert(Math.abs(number(await text('net-worth')) - expectedWorth) < 0.02);
    await assertCount();
    await page.getByRole('button', { name: 'DEX 过滤', exact: true }).click();
    await page.getByRole('button', { name: 'Curve', exact: true }).click();
    assert.equal(await assertCount(), 1);
    assert.equal(await page.locator('body').evaluate((body) => body.innerText.includes('→')), false);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: '余额 & 兑换', exact: true }).click();
    await demo('可兑换');
    await page.screenshot({ path: 'artifacts/mobile.png' });
    assert(await page.getByText('我的钱包', { exact: true }).isVisible());
    assert(await page.getByRole('button', { name: '演示状态', exact: true }).isVisible());
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.deepEqual(errors, []);
    console.log('PASS: 钱包合计、收付双行、确认递增、实时推送、筛选计数、路由、MAX、滑点、七种状态、授权、模拟成交记账、移动端。');
  } finally {
    await browser.close();
  }
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
